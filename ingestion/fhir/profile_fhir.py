"""
Profile Synthea FHIR R4 bundles before designing the bronze load (FHIR-1, discovery).

Answers, for every file in the source folder:
  1. Which resource types exist, how many, and how many MB each (what to load, what to skip)
  2. Which code systems each clinical/financial resource uses (what conversion is needed)
  3. What date range the data covers, and how many patients there are
  4. Which files are patient bundles vs shared reference bundles (by CONTENT, not file name)

Reads one file at a time, so memory stays at the size of the largest single file.

Run from the project root:
    python ingestion/fhir/profile_fhir.py
Output: docs/profiling/fhir_profile.md
"""
from __future__ import annotations

import json
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

SOURCE_DIR = Path("data/source/synthea/fhir")
OUTPUT = Path("docs/profiling/fhir_profile.md")

# Where the "main" code lives in each resource type we may map to silver.
CODE_PATHS = {
    "Condition": lambda r: [r.get("code")],
    "Procedure": lambda r: [r.get("code")],
    "Encounter": lambda r: r.get("type", []),
    "MedicationRequest": lambda r: [r.get("medicationCodeableConcept")],
    "Observation": lambda r: [r.get("code")],
    "Immunization": lambda r: [r.get("vaccineCode")],
    "Claim": lambda r: [i.get("productOrService") for i in r.get("item", [])],
    "ExplanationOfBenefit": lambda r: [i.get("productOrService") for i in r.get("item", [])],
}
# Dates used to measure coverage period, per resource type.
DATE_PATHS = {
    "Encounter": lambda r: (r.get("period") or {}).get("start"),
    "Claim": lambda r: (r.get("billablePeriod") or {}).get("start"),
}


def code_systems(concepts) -> list[str]:
    systems = []
    for concept in concepts or []:
        for coding in (concept or {}).get("coding", []):
            systems.append(coding.get("system", "(none)"))
    return systems


def main() -> int:
    files = sorted(SOURCE_DIR.glob("*.json"))
    if not files:
        print(f"No .json files in {SOURCE_DIR}", file=sys.stderr)
        return 1

    started = time.time()
    type_count, type_bytes = Counter(), Counter()
    systems = defaultdict(Counter)
    file_kinds = Counter()
    shared_files, bad_files = [], []
    min_date, max_date = {}, {}
    entries_total = 0
    largest = (0, "")

    for n, path in enumerate(files, 1):
        size = path.stat().st_size
        largest = max(largest, (size, path.name))
        try:
            bundle = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError) as exc:
            bad_files.append(f"{path.name}: {exc}")
            continue

        entries = bundle.get("entry", [])
        entries_total += len(entries)
        types_here = {e.get("resource", {}).get("resourceType") for e in entries}
        if "Patient" in types_here:
            file_kinds["patient bundle"] += 1
        else:
            file_kinds["shared reference bundle"] += 1
            shared_files.append(f"{path.name} ({', '.join(sorted(t for t in types_here if t))})")

        for entry in entries:
            res = entry.get("resource", {})
            rtype = res.get("resourceType", "(missing)")
            type_count[rtype] += 1
            type_bytes[rtype] += len(json.dumps(res, separators=(",", ":")))
            if rtype in CODE_PATHS:
                systems[rtype].update(code_systems(CODE_PATHS[rtype](res)))
            if rtype in DATE_PATHS:
                d = (DATE_PATHS[rtype](res) or "")[:10]
                if d:
                    min_date[rtype] = min(min_date.get(rtype, d), d)
                    max_date[rtype] = max(max_date.get(rtype, d), d)

        if n % 100 == 0:
            print(f"  {n}/{len(files)} files ({time.time() - started:.0f}s)", flush=True)

    total_bytes = sum(type_bytes.values()) or 1
    out = [
        "# Synthea FHIR R4 Source Profile",
        "",
        f"**Source:** `{SOURCE_DIR}`  ",
        f"**Generated by:** `ingestion/fhir/profile_fhir.py` in {time.time() - started:.0f}s",
        "",
        "## Files",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Files | {len(files):,} |",
        *[f"| {kind} | {cnt:,} |" for kind, cnt in file_kinds.most_common()],
        f"| Unreadable files | {len(bad_files)} |",
        f"| Bundle entries (resources) | {entries_total:,} |",
        f"| Largest file | {largest[1]} ({largest[0] / 1e6:.1f} MB) |",
        "",
        "Shared reference bundles (identified by content: no Patient resource):",
        "",
        *[f"- {s}" for s in shared_files],
        *([""] + ["Unreadable:"] + [f"- {b}" for b in bad_files] if bad_files else []),
        "",
        "## Resource types",
        "",
        "| Resource type | Count | MB (compact JSON) | % of volume |",
        "|---|---:|---:|---:|",
        *[
            f"| {t} | {c:,} | {type_bytes[t] / 1e6:,.1f} | {100 * type_bytes[t] / total_bytes:.1f} |"
            for t, c in sorted(type_count.items(), key=lambda kv: -type_bytes[kv[0]])
        ],
        "",
        "## Code systems by resource type",
        "",
        "| Resource type | Code system | Codings |",
        "|---|---|---:|",
        *[
            f"| {t} | `{s}` | {c:,} |"
            for t in sorted(systems)
            for s, c in systems[t].most_common()
        ],
        "",
        "## Date coverage",
        "",
        "| Resource type | Earliest | Latest |",
        "|---|---|---|",
        *[f"| {t} | {min_date[t]} | {max_date[t]} |" for t in sorted(min_date)],
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
